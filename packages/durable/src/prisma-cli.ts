#!/usr/bin/env node
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { prismaDurableModelNames, prismaDurableSchema } from "./prisma-schema.js";
import { isMain, runGeneratorCli, type CliIo } from "./cli-shared.js";

export const prismaSpec = {
  bin: "anvia-durable-prisma",
  fileName: "anvia-durable.prisma",
  header: "// Generated by @anvia/durable. Review before running Prisma migrations.",
  startMarker: "// BEGIN ANVIA DURABLE PRISMA MODELS",
  endMarker: "// END ANVIA DURABLE PRISMA MODELS",
  names: prismaDurableModelNames,
  body: prismaDurableSchema,
  defaultSchema: schemaFromConfig,
  next: ["npx prisma format", "npx prisma migrate dev --name anvia-durable", "npx prisma generate"],
};

function schemaFromConfig(cwd: string): string {
  const config = resolve(cwd, "prisma.config.ts");
  if (existsSync(config)) {
    const match = readFileSync(config, "utf8").match(/\bschema\s*:\s*["']([^"']+)["']/);
    if (match?.[1] !== undefined) return resolve(cwd, match[1]);
  }
  return resolve(cwd, "prisma", "schema.prisma");
}

export function runCli(
  argv: string[] = process.argv.slice(2),
  cwd = process.cwd(),
  io: CliIo = console,
): Promise<number> {
  return runGeneratorCli(prismaSpec, argv, cwd, io);
}

if (isMain(import.meta.url)) {
  runCli().then((code) => {
    process.exitCode = code;
  });
}
