#!/usr/bin/env node
import { existsSync, readFileSync } from "node:fs";
import { extname, join, resolve } from "node:path";
import { drizzleDurableExportNames } from "./drizzle-schema.js";
import { isMain, runGeneratorCli, type CliIo } from "./cli-shared.js";

const header = "// Generated by @anvia/durable. Review before running Drizzle migrations.";

export const drizzleSpec = {
  bin: "anvia-durable-drizzle",
  fileName: "anvia-durable.ts",
  header,
  startMarker: "// BEGIN ANVIA DURABLE DRIZZLE SCHEMA",
  endMarker: "// END ANVIA DURABLE DRIZZLE SCHEMA",
  names: drizzleDurableExportNames,
  body: `export {\n${drizzleDurableExportNames.map((name) => `  ${name},`).join("\n")}\n} from "@anvia/durable/drizzle";\n`,
  defaultSchema: schemaFromConfig,
  next: [
    "Ensure the generated file is included by the schema setting in drizzle.config.ts",
    "npx drizzle-kit generate",
    "npx drizzle-kit migrate",
  ],
};

function schemaFromConfig(cwd: string): string {
  for (const name of [
    "drizzle.config.ts",
    "drizzle.config.mts",
    "drizzle.config.js",
    "drizzle.config.mjs",
  ]) {
    const path = resolve(cwd, name);
    if (!existsSync(path)) continue;
    const match = readFileSync(path, "utf8").match(/\bschema\s*:\s*["']([^"']+)["']/);
    if (match?.[1] === undefined || /[*?{}[\]]/.test(match[1])) continue;
    const found = resolve(cwd, match[1]);
    return [".ts", ".js", ".mts", ".mjs", ".cts", ".cjs"].includes(extname(found))
      ? found
      : join(found, "schema.ts");
  }
  return resolve(cwd, "src", "db", "schema.ts");
}

export function runCli(
  argv: string[] = process.argv.slice(2),
  cwd = process.cwd(),
  io: CliIo = console,
): Promise<number> {
  return runGeneratorCli(drizzleSpec, argv, cwd, io);
}

if (isMain(import.meta.url)) {
  runCli().then((code) => {
    process.exitCode = code;
  });
}
